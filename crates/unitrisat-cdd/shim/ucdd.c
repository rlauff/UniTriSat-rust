/* Project shim over cddlib 0.94n (GMPRATIONAL build) for unitrisat-cdd.
 *
 * Rust never sees cddlib's struct layouts: it holds opaque matrix and LP
 * pointers and moves numbers through mpq_t. Indices are zero-based here and
 * every index is checked by the Rust caller before the call. The caller calls
 * ucdd_init exactly once before anything else; after that, different threads
 * may call these functions at the same time on different objects (see the
 * thread-safety notes in src/ffi.rs and vendor/PATCHES.json).
 */
/* The include order of cddlib's own units. */
#include "setoper.h"
#include "cdd.h"
#include <stdio.h>
#include <stdlib.h>
#include <time.h>
#include <math.h>
#include <string.h>

void ucdd_init(void) { dd_set_global_constants(); }

/* A rows x cols matrix of zeros: 1 = inequalities, 2 = generators. */
dd_MatrixPtr ucdd_matrix_new(long rows, long cols, int representation)
{
  dd_MatrixPtr m = dd_CreateMatrix(rows, cols);
  if (m != NULL) {
    m->representation = representation == 2 ? dd_Generator : dd_Inequality;
    m->numbtype = dd_Rational;
  }
  return m;
}

void ucdd_matrix_free(dd_MatrixPtr m) { dd_FreeMatrix(m); }

long ucdd_matrix_rows(dd_MatrixPtr m) { return m->rowsize; }

long ucdd_matrix_cols(dd_MatrixPtr m) { return m->colsize; }

void ucdd_matrix_set(dd_MatrixPtr m, long row, long col, mpq_srcptr value)
{
  mpq_set(m->matrix[row][col], value);
}

void ucdd_matrix_get(dd_MatrixPtr m, long row, long col, mpq_ptr out)
{
  mpq_set(out, m->matrix[row][col]);
}

void ucdd_matrix_set_linearity(dd_MatrixPtr m, long row) { set_addelem(m->linset, row + 1); }

int ucdd_matrix_is_linearity(dd_MatrixPtr m, long row) { return set_member(row + 1, m->linset); }

/* Objective: 1 = maximize, 2 = minimize; the row has `cols` entries. */
void ucdd_matrix_set_objective(dd_MatrixPtr m, int sense)
{
  m->objective = sense == 2 ? dd_LPmin : dd_LPmax;
}

void ucdd_matrix_set_objective_entry(dd_MatrixPtr m, long col, mpq_srcptr value)
{
  mpq_set(m->rowvec[col], value);
}

/* The inequalities of the polytope or cone generated by `generators`.
 * Returns NULL and sets *err to a cddlib error code on failure. */
dd_MatrixPtr ucdd_inequalities(dd_MatrixPtr generators, int *err)
{
  dd_ErrorType e = dd_NoError;
  dd_PolyhedraPtr poly = dd_DDMatrix2Poly(generators, &e);
  dd_MatrixPtr result = NULL;
  if (poly != NULL && e == dd_NoError) {
    result = dd_CopyInequalities(poly);
  }
  if (poly != NULL) {
    dd_FreePolyhedra(poly);
  }
  *err = (int)e;
  return result;
}

/* Solves the LP of an inequality matrix with its objective. Returns NULL and
 * sets *err on failure. */
dd_LPPtr ucdd_lp_solve(dd_MatrixPtr m, int *err)
{
  dd_ErrorType e = dd_NoError;
  dd_LPPtr lp = dd_Matrix2LP(m, &e);
  if (lp == NULL || e != dd_NoError) {
    if (lp != NULL) {
      dd_FreeLPData(lp);
    }
    *err = (int)e;
    return NULL;
  }
  dd_LPSolve(lp, dd_DualSimplex, &e);
  *err = (int)e;
  if (e != dd_NoError) {
    dd_FreeLPData(lp);
    return NULL;
  }
  return lp;
}

void ucdd_lp_free(dd_LPPtr lp) { dd_FreeLPData(lp); }

int ucdd_lp_status(dd_LPPtr lp) { return (int)lp->LPS; }

long ucdd_lp_cols(dd_LPPtr lp) { return lp->d; }

void ucdd_lp_value(dd_LPPtr lp, mpq_ptr out) { mpq_set(out, lp->optvalue); }

void ucdd_lp_solution(dd_LPPtr lp, long col, mpq_ptr out) { mpq_set(out, lp->sol[col]); }

/* For the shared-GMP test: the mpq_set this C code links against, and the
 * gmp.h version it was compiled with. */
void (*ucdd_gmp_mpq_set(void))(mpq_ptr, mpq_srcptr) { return &mpq_set; }

int ucdd_gmp_header_version(void)
{
  return __GNU_MP_VERSION * 10000 + __GNU_MP_VERSION_MINOR * 100 + __GNU_MP_VERSION_PATCHLEVEL;
}
