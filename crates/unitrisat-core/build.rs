//! Generates the straight-line kernels used by `intersect` (the Rust
//! counterpart of the Julia `@generate_*` macros in `cpu_intersection.jl`):
//!
//! * `det{k}`: division-free Laplace determinants for k = 1..=9,
//! * `impl Gcross<D> for Dims`: generalized cross products for D = 2..=10,
//! * `COORD_BOUND_I64` / `COORD_BOUND_I128`: largest coordinate magnitude for
//!   which every kernel intermediate provably fits the integer type,
//! * `WITNESS_STEPS`: the sampling of the segment witness, which the bounds
//!   account for,
//! * `faces`, `subsets`, `small_det`, `cross_terms`: tables for the
//!   table-driven cross axes of dimensions above 6,
//! * `impl CrossAxes<D, D + 1> for Dims`: the cross-axis enumeration, with
//!   straight-line minors and axis components up to dimension 6.

use std::{env, fmt::Write as _, fs, path::PathBuf};

const MIN_D: usize = 2;
const MAX_D: usize = 10;
/// Largest dimension whose cross-axis code is generated (as Julia's
/// `@generate_cross_axes_case_scalar`); larger dimensions use the
/// table-driven loop in `intersect.rs`, which compiles far faster and keeps
/// stack frames small.
const UNROLL_MAX_D: usize = 6;
/// Largest determinant size whose code is force-inlined.
const INLINE_MAX_K: usize = 5;
/// The segment witness tries `(i c_a + (N - i) c_b) / N` for `i = 1..N`.
const WITNESS_STEPS: u32 = 8;

fn main() {
    let mut out = String::new();
    out.push_str("// @generated by build.rs; do not edit.\n");
    for k in 1..MAX_D {
        emit_det(&mut out, k);
    }
    for d in MIN_D..=MAX_D {
        emit_gcross(&mut out, d);
    }
    emit_faces(&mut out);
    emit_small_det(&mut out);
    emit_subsets(&mut out);
    emit_cross_terms(&mut out);
    emit_bounds(&mut out);
    for d in MIN_D..=MAX_D {
        emit_cross_axes(&mut out, d);
    }
    let dir = PathBuf::from(env::var_os("OUT_DIR").unwrap_or_default());
    if let Err(error) = fs::write(dir.join("intersect_gen.rs"), out) {
        eprintln!("failed to write generated kernels: {error}");
        std::process::exit(1);
    }
    println!("cargo::rerun-if-changed=build.rs");
}

fn m(i: usize, j: usize) -> String {
    format!("m{i}_{j}")
}

/// `det{k}(m0_0, m0_1, ..., m{k-1}_{k-1})`, arguments in row-major order.
fn emit_det(out: &mut String, k: usize) {
    let params: Vec<String> = (0..k)
        .flat_map(|i| (0..k).map(move |j| format!("{}: T", m(i, j))))
        .collect();
    // Force inlining only up to 5x5 (D <= 6, the hot dimensions). Larger
    // determinants stay calls: fully inlining a k x k Laplace expansion grows
    // like k! and makes compilation explode.
    let inline = if k <= INLINE_MAX_K {
        "#[inline(always)]"
    } else {
        "#[inline(never)]"
    };
    let _ = writeln!(out, "{inline}");
    let _ = writeln!(
        out,
        "#[allow(clippy::too_many_arguments, clippy::many_single_char_names)]"
    );
    let _ = writeln!(out, "fn det{k}<T: Lane>({}) -> T {{", params.join(", "));
    if k == 1 {
        let _ = writeln!(out, "    m0_0");
    } else {
        // Laplace expansion along row 0.
        let mut terms = Vec::new();
        for j in 0..k {
            let minor: Vec<String> = (1..k)
                .flat_map(|i| (0..k).filter(move |&c| c != j).map(move |c| m(i, c)))
                .collect();
            terms.push((
                j % 2 == 1,
                format!("{}.mul(det{}({}))", m(0, j), k - 1, minor.join(", ")),
            ));
        }
        let mut expr = terms[0].1.clone();
        for (negative, term) in &terms[1..] {
            expr = format!("{expr}.{}({term})", if *negative { "sub" } else { "add" });
        }
        let _ = writeln!(out, "    {expr}");
    }
    let _ = writeln!(out, "}}\n");
}

/// Component `i` of the normal of the hyperplane spanned by `span[0..d-1]`
/// (vectors as rows) is `(-1)^i det(minor without component i)`.
fn emit_gcross(out: &mut String, d: usize) {
    let _ = writeln!(out, "impl Gcross<{d}> for Dims {{");
    let inline = if d <= INLINE_MAX_K + 1 {
        "#[inline(always)]"
    } else {
        "#[inline]"
    };
    let _ = writeln!(out, "    {inline}");
    let _ = writeln!(
        out,
        "    fn gcross<T: Lane>(span: &[[T; {d}]; {d}]) -> [T; {d}] {{"
    );
    let mut comps = Vec::new();
    for i in 0..d {
        // Matrix rows = remaining components, columns = spanning vectors.
        let args: Vec<String> = (0..d)
            .filter(|&r| r != i)
            .flat_map(|r| (0..d - 1).map(move |c| format!("span[{c}][{r}]")))
            .collect();
        let det = format!("det{}({})", d - 1, args.join(", "));
        comps.push(if i % 2 == 1 {
            format!("{det}.neg()")
        } else {
            det
        });
    }
    let _ = writeln!(out, "        [{}]", comps.join(",\n         "));
    let _ = writeln!(out, "    }}\n}}\n");
}

/// All `k`-subsets of `0..n` in lexicographic order.
fn combinations(n: usize, k: usize) -> Vec<Vec<usize>> {
    fn extend(
        start: usize,
        n: usize,
        k: usize,
        current: &mut Vec<usize>,
        all: &mut Vec<Vec<usize>>,
    ) {
        if current.len() == k {
            all.push(current.clone());
            return;
        }
        for x in start..n {
            current.push(x);
            extend(x + 1, n, k, current, all);
            current.pop();
        }
    }
    let mut all = Vec::new();
    extend(0, n, k, &mut Vec::new(), &mut all);
    all
}

/// Flat `size`-subsets of `0..vertices`, for every simplex size used by the
/// cross-axis loops (vertices = D + 1, size = 2..=D - 1).
fn emit_faces(out: &mut String) {
    let _ = writeln!(
        out,
        "/// All `size`-subsets of `0..vertices`, flattened with stride `size`."
    );
    let _ = writeln!(
        out,
        "fn faces(vertices: usize, size: usize) -> &'static [u8] {{"
    );
    let _ = writeln!(out, "    match (vertices, size) {{");
    for d in MIN_D..=MAX_D {
        let v = d + 1;
        for size in 2..d {
            let flat: Vec<String> = combinations(v, size)
                .into_iter()
                .flatten()
                .map(|x| x.to_string())
                .collect();
            let _ = writeln!(out, "        ({v}, {size}) => &[{}],", flat.join(", "));
        }
    }
    let _ = writeln!(out, "        _ => &[],\n    }}\n}}\n");
}

/// Largest minor size used by the cross-axis expansion (`D - 2`).
const MAX_MINOR: usize = MAX_D - 2;

/// `small_det(m, k)`: determinant of the leading `k x k` block of `m`.
fn emit_small_det(out: &mut String) {
    let _ = writeln!(out, "/// Largest minor size of the cross-axis expansion.");
    let _ = writeln!(out, "const MAX_MINOR: usize = {MAX_MINOR};\n");
    let _ = writeln!(
        out,
        "/// Determinant of the leading `k x k` block of `m`; `None` if `k` is unsupported."
    );
    let _ = writeln!(out, "#[inline(always)]");
    let _ = writeln!(
        out,
        "fn small_det<T: Lane>(m: &[[T; {MAX_MINOR}]; {MAX_MINOR}], k: usize) -> Option<T> {{"
    );
    let _ = writeln!(out, "    match k {{");
    for k in 1..=MAX_MINOR {
        let args: Vec<String> = (0..k)
            .flat_map(|i| (0..k).map(move |j| format!("m[{i}][{j}]")))
            .collect();
        let _ = writeln!(out, "        {k} => Some(det{k}({})),", args.join(", "));
    }
    let _ = writeln!(out, "        _ => None,\n    }}\n}}\n");
}

/// `subsets(d, size)`: all `size`-subsets of the coordinate indices `0..d`,
/// flattened with stride `size` (lexicographic order).
fn emit_subsets(out: &mut String) {
    let _ = writeln!(
        out,
        "/// All `size`-subsets of `0..d`, flattened with stride `size`."
    );
    let _ = writeln!(out, "fn subsets(d: usize, size: usize) -> &'static [u8] {{");
    let _ = writeln!(out, "    match (d, size) {{");
    for d in MIN_D..=MAX_D {
        for size in 1..d.saturating_sub(1) {
            let flat: Vec<String> = combinations(d, size)
                .into_iter()
                .flatten()
                .map(|x| x.to_string())
                .collect();
            let _ = writeln!(out, "        ({d}, {size}) => &[{}],", flat.join(", "));
        }
    }
    let _ = writeln!(out, "        _ => &[],\n    }}\n}}\n");
}

/// Generalized Laplace expansion of the cross product of `k` vectors `a` and
/// `l = d - 1 - k` vectors `b`. Component `i` is the sum over its terms
/// `(ia, ib, positive)` of `+-A[ia] * B[ib]`, where `A[ia]` is the `k x k`
/// minor of the `a` vectors on coordinate subset `ia` (index into
/// `subsets(d, k)`) and `B[ib]` the `l x l` minor of the `b` vectors on subset
/// `ib` (index into `subsets(d, l)`). Each component has `C(d-1, k)` terms;
/// components are stored consecutively.
fn emit_cross_terms(out: &mut String) {
    let _ = writeln!(
        out,
        "/// Expansion terms `(a_minor, b_minor, positive)`, grouped per component."
    );
    let _ = writeln!(
        out,
        "fn cross_terms(d: usize, k: usize) -> &'static [(u16, u16, bool)] {{"
    );
    let _ = writeln!(out, "    match (d, k) {{");
    for d in MIN_D..=MAX_D {
        for k in 1..d.saturating_sub(1) {
            let l = d - 1 - k;
            let sub_k = combinations(d, k);
            let sub_l = combinations(d, l);
            let mut terms = Vec::new();
            for i in 0..d {
                let rows: Vec<usize> = (0..d).filter(|&r| r != i).collect();
                for positions in combinations(d - 1, k) {
                    let set_a: Vec<usize> = positions.iter().map(|&p| rows[p]).collect();
                    let set_b: Vec<usize> = (0..d - 1)
                        .filter(|p| !positions.contains(p))
                        .map(|p| rows[p])
                        .collect();
                    let ia = sub_k.iter().position(|s| *s == set_a).unwrap_or(usize::MAX);
                    let ib = sub_l.iter().position(|s| *s == set_b).unwrap_or(usize::MAX);
                    // Laplace sign along the first k columns, times (-1)^i
                    // from the cross-product convention.
                    let parity = positions.iter().sum::<usize>() + (0..k).sum::<usize>() + i;
                    terms.push(format!("({ia}, {ib}, {})", parity % 2 == 0));
                }
            }
            let _ = writeln!(out, "        ({d}, {k}) => &[{}],", terms.join(", "));
        }
    }
    let _ = writeln!(out, "        _ => &[],\n    }}\n}}\n");
}

/// Upper bound on |det| of a j x j matrix with entries bounded by `m`:
/// min(Hadamard, Leibniz). `None` on u128 overflow.
fn det_bound(j: u32, m: u128) -> Option<u128> {
    if j == 0 {
        return Some(1);
    }
    let jj = u128::from(j).checked_pow(j)?;
    let hadamard = jj.isqrt() + 1;
    let leibniz = (1..=u128::from(j)).product::<u128>();
    hadamard.min(leibniz).checked_mul(m.checked_pow(j)?)
}

/// Every intermediate of the kernel at dimension `d` with coordinates
/// bounded by `b` stays within `max`:
/// * Laplace partial sums of a k x k determinant (entries <= 2b) are bounded
///   by `k * 2b * det_bound(k - 1)`, for k = 1..=d-1;
/// * projections and orientation tests `dot(normal, x)` with |x| <= 2b are
///   bounded by `d * 2b * det_bound(d - 1)`.
fn fits(d: u32, b: u128, max: u128) -> bool {
    let check = || -> Option<bool> {
        let m = b.checked_mul(2)?;
        for k in 1..d {
            let partial = u128::from(k)
                .checked_mul(m)?
                .checked_mul(det_bound(k - 1, m)?)?;
            if partial > max {
                return Some(false);
            }
        }
        // Generalized Laplace sums of the cross axes:
        // C(d-1, k) * det_bound(k) * det_bound(d-1-k).
        for k in 1..d.saturating_sub(1) {
            let l = d - 1 - k;
            let terms = binomial(d - 1, k)?;
            let sum = terms
                .checked_mul(det_bound(k, m)?)?
                .checked_mul(det_bound(l, m)?)?;
            if sum > max {
                return Some(false);
            }
        }
        let dot = u128::from(d)
            .checked_mul(m)?
            .checked_mul(det_bound(d - 1, m)?)?;
        // Segment witness: dot(normal, i * sum_a + (N - i) * sum_b) and
        // N * (d + 1) * facet offset, both bounded by
        // N * d * (d + 1) * b * det_bound(d - 1).
        let witness = u128::from(WITNESS_STEPS)
            .checked_mul(u128::from(d))?
            .checked_mul(u128::from(d) + 1)?
            .checked_mul(b)?
            .checked_mul(det_bound(d - 1, m)?)?;
        Some(dot <= max && witness <= max)
    };
    check().unwrap_or(false)
}

fn binomial(n: u32, k: u32) -> Option<u128> {
    let mut result: u128 = 1;
    for i in 0..u128::from(k) {
        result = result.checked_mul(u128::from(n) - i)? / (i + 1);
    }
    Some(result)
}

fn max_coord(d: u32, max: u128) -> u128 {
    let (mut lo, mut hi) = (0_u128, 1_u128 << 62);
    while lo < hi {
        let mid = lo + (hi - lo).div_ceil(2);
        if fits(d, mid, max) {
            lo = mid;
        } else {
            hi = mid - 1;
        }
    }
    lo
}

fn emit_bounds(out: &mut String) {
    let max_i64 = u128::try_from(i64::MAX).unwrap_or(0);
    let max_i128 = u128::try_from(i128::MAX).unwrap_or(0);
    let mut b64 = vec!["0".to_owned(); MAX_D + 1];
    let mut b128 = vec!["0".to_owned(); MAX_D + 1];
    for d in MIN_D..=MAX_D {
        let dd = u32::try_from(d).unwrap_or(0);
        b64[d] = max_coord(dd, max_i64)
            .min(u128::try_from(i64::MAX).unwrap_or(0))
            .to_string();
        b128[d] = max_coord(dd, max_i128)
            .min(u128::try_from(i64::MAX).unwrap_or(0))
            .to_string();
    }
    let _ = writeln!(
        out,
        "/// Points tried on the segment between the centroids, plus one."
    );
    let _ = writeln!(out, "const WITNESS_STEPS: i64 = {WITNESS_STEPS};");
    let _ = writeln!(
        out,
        "/// Largest |coordinate| for the `i64` kernel, indexed by dimension."
    );
    let _ = writeln!(
        out,
        "const COORD_BOUND_I64: [i64; {}] = [{}];",
        MAX_D + 1,
        b64.join(", ")
    );
    let _ = writeln!(
        out,
        "/// Largest |coordinate| for the `i128` kernel, indexed by dimension."
    );
    let _ = writeln!(
        out,
        "const COORD_BOUND_I128: [i64; {}] = [{}];",
        MAX_D + 1,
        b128.join(", ")
    );
}

/// The minors of the spanning vectors `e0..e{size-1}` on every coordinate
/// subset of `0..d` of that size, as an array expression.
fn minors_expr(d: usize, size: usize) -> String {
    let minors: Vec<String> = combinations(d, size)
        .into_iter()
        .map(|subset| {
            if size == 1 {
                return format!("e0[{}]", subset[0]);
            }
            // Matrix rows = coordinates of the subset, columns = vectors.
            let args: Vec<String> = subset
                .iter()
                .flat_map(|&c| (0..size).map(move |v| format!("e{v}[{c}]")))
                .collect();
            format!("det{size}({})", args.join(", "))
        })
        .collect();
    format!("[{}]", minors.join(", "))
}

/// `impl CrossAxes<d, d + 1> for Dims`: whether some generalized cross product
/// of a k-face of `a` and an l-face of `b` (k + l = d - 1) separates them.
/// Up to `UNROLL_MAX_D`, each k gets its own function `cross{d}_{k}` whose
/// minors and axis components are straight-line code; the faces are looped
/// over from constant tables.
fn emit_cross_axes(out: &mut String, d: usize) {
    let v = d + 1;
    if d > UNROLL_MAX_D {
        let _ = writeln!(out, "impl CrossAxes<{d}, {v}> for Dims {{");
        let _ = writeln!(
            out,
            "    fn cross_separated<T: Lane>(a: &[[T; {d}]; {v}], b: &[[T; {d}]; {v}]) -> Option<bool> {{"
        );
        let _ = writeln!(out, "        cross_separated_generic(a, b)\n    }}\n}}\n");
        return;
    }
    for k in 1..d.saturating_sub(1) {
        emit_cross_k(out, d, k);
    }
    let calls: Vec<String> = (1..d.saturating_sub(1))
        .map(|k| format!("cross{d}_{k}(a, b)"))
        .collect();
    let _ = writeln!(out, "impl CrossAxes<{d}, {v}> for Dims {{");
    let _ = writeln!(out, "    #[inline(always)]");
    let _ = writeln!(
        out,
        "    fn cross_separated<T: Lane>(a: &[[T; {d}]; {v}], b: &[[T; {d}]; {v}]) -> Option<bool> {{"
    );
    match calls.as_slice() {
        // Dimension 2 has no cross axes.
        [] => {
            let _ = writeln!(out, "        let _ = (a, b);\n        Some(false)");
        }
        [single] => {
            let _ = writeln!(out, "        {single}");
        }
        _ => {
            let checked: Vec<String> = calls.iter().map(|c| format!("{c}?")).collect();
            let _ = writeln!(out, "        Some({})", checked.join(" || "));
        }
    }
    let _ = writeln!(out, "    }}\n}}\n");
}

/// Binds `o` and `e0..` to the origin and spanning vectors of `face` (a row
/// of a face table) in `simplex`.
fn face_vectors_dyn(simplex: &str, size: usize) -> String {
    let names: Vec<String> = (0..size).map(|i| format!("i{i}")).collect();
    let mut code = format!(
        "let [{}] = face.map(usize::from); let o = {simplex}.get(i0)?;",
        names.join(", ")
    );
    for v in 1..size {
        code.push_str(&format!(
            " let e{} = sub_vec({simplex}.get(i{v})?, o);",
            v - 1
        ));
    }
    code
}

/// `cross{d}_{k}`: the cross axes of the k-faces of `a` and the
/// (d - 1 - k)-faces of `b`. `None` only if a face table is malformed.
fn emit_cross_k(out: &mut String, d: usize, k: usize) {
    let v = d + 1;
    let l = d - 1 - k;
    let sub_k = combinations(d, k).len();
    let sub_l = combinations(d, l).len();
    let faces_k = combinations(v, k + 1);
    let faces_l = combinations(v, l + 1);
    // Generalized Laplace expansion along the first k columns: component i
    // is the sum over the k-subsets of the remaining rows of
    // +-(k x k minor of the a-face) * (l x l minor of the b-face), with the
    // Laplace sign times (-1)^i from the cross-product convention.
    let components: Vec<String> = (0..d)
        .map(|i| {
            let rows: Vec<usize> = (0..d).filter(|&r| r != i).collect();
            let mut expr = String::new();
            for (n, positions) in combinations(d - 1, k).into_iter().enumerate() {
                let set_a: Vec<usize> = positions.iter().map(|&p| rows[p]).collect();
                let set_b: Vec<usize> = (0..d - 1)
                    .filter(|p| !positions.contains(p))
                    .map(|p| rows[p])
                    .collect();
                let ia = combinations(d, k)
                    .iter()
                    .position(|s| *s == set_a)
                    .unwrap_or(0);
                let ib = combinations(d, l)
                    .iter()
                    .position(|s| *s == set_b)
                    .unwrap_or(0);
                let parity = positions.iter().sum::<usize>() + (0..k).sum::<usize>() + i;
                let product = format!("am[{ia}].mul(m[{ib}])");
                expr = match (n, parity % 2 == 0) {
                    (0, true) => product,
                    (0, false) => format!("{product}.neg()"),
                    (_, true) => format!("{expr}.add({product})"),
                    (_, false) => format!("{expr}.sub({product})"),
                };
            }
            expr
        })
        .collect();
    let table = |faces: &[Vec<usize>]| -> String {
        let rows: Vec<String> = faces
            .iter()
            .map(|f| {
                let items: Vec<String> = f.iter().map(ToString::to_string).collect();
                format!("[{}]", items.join(", "))
            })
            .collect();
        rows.join(", ")
    };
    let _ = writeln!(out, "#[inline(always)]");
    let _ = writeln!(
        out,
        "fn cross{d}_{k}<T: Lane>(a: &[[T; {d}]; {v}], b: &[[T; {d}]; {v}]) -> Option<bool> {{"
    );
    let _ = writeln!(
        out,
        "    static FACES_A: [[u8; {}]; {}] = [{}];",
        k + 1,
        faces_k.len(),
        table(&faces_k)
    );
    let _ = writeln!(
        out,
        "    static FACES_B: [[u8; {}]; {}] = [{}];",
        l + 1,
        faces_l.len(),
        table(&faces_l)
    );
    let _ = writeln!(
        out,
        "    let mut bm = [[T::ZERO; {sub_l}]; {}];",
        faces_l.len()
    );
    let _ = writeln!(
        out,
        "    for (minors, face) in bm.iter_mut().zip(&FACES_B) {{"
    );
    let _ = writeln!(out, "        {}", face_vectors_dyn("b", l + 1));
    let _ = writeln!(out, "        *minors = {};", minors_expr(d, l));
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "    for face in &FACES_A {{");
    let _ = writeln!(out, "        {}", face_vectors_dyn("a", k + 1));
    let _ = writeln!(out, "        let am: [T; {sub_k}] = {};", minors_expr(d, k));
    let _ = writeln!(out, "        for m in &bm {{");
    let _ = writeln!(out, "            let axis = [{}];", components.join(", "));
    let _ = writeln!(
        out,
        "            if !is_zero(&axis) && separates(a, b, &axis) {{ return Some(true); }}"
    );
    let _ = writeln!(out, "        }}");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "    Some(false)\n}}\n");
}
