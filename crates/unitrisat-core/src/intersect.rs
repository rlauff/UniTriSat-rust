//! Exact interior-intersection test for lattice simplices, by separating axes.
//!
//! Port of `src/Intersection_backends/cpu_intersection.jl`. Two
//! `D`-simplices are reported as intersecting exactly when no candidate axis
//! separates them. The candidates are the coordinate axes (bounding-box
//! prefilter), the facet normals of both simplices, and the generalized cross
//! products of every pair of a `k`-face of one simplex and a `(D-1-k)`-face of
//! the other. Touching counts as separated (`max <= min`), so only interior
//! overlap is reported.
//!
//! All arithmetic is exact. Coordinates are checked against a per-dimension
//! bound (generated by `build.rs`) that keeps every intermediate inside `i64`;
//! inputs above it use an `i128` kernel with its own bound, and inputs above
//! that are rejected. Within those bounds the kernel's wrapping operations
//! never actually wrap.

use rayon::prelude::*;
use std::sync::{
    Condvar, Mutex, PoisonError,
    atomic::{AtomicBool, AtomicUsize, Ordering},
};

include!(concat!(env!("OUT_DIR"), "/intersect_gen.rs"));

/// Smallest supported dimension.
pub const MIN_DIMENSION: usize = 2;
/// Largest supported dimension.
pub const MAX_DIMENSION: usize = 10;

/// Below this many simplices the pair search runs serially.
const PARALLEL_THRESHOLD: usize = 128;

/// Errors of the intersection stage.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum IntersectError {
    /// The dimension is outside `MIN_DIMENSION..=MAX_DIMENSION`.
    #[error("dimension {0} is not supported (supported: 2..=10)")]
    UnsupportedDimension(usize),
    /// The point matrix length is not a multiple of the dimension.
    #[error("point matrix has {len} values, which is not a multiple of dimension {dimension}")]
    PointShape {
        /// Number of coordinate values given.
        len: usize,
        /// Dimension.
        dimension: usize,
    },
    /// The simplex list length is not a multiple of `dimension + 1`.
    #[error("simplex list has {len} labels, which is not a multiple of {vertices}")]
    SimplexShape {
        /// Number of labels given.
        len: usize,
        /// Vertices per simplex.
        vertices: usize,
    },
    /// A simplex references a point that does not exist.
    #[error("simplex {simplex} references point {label}, but there are only {points} points")]
    PointOutOfRange {
        /// Zero-based simplex index.
        simplex: usize,
        /// The offending point label.
        label: u32,
        /// Number of points.
        points: usize,
    },
    /// Coordinates are too large for an exact computation.
    #[error("|coordinate| up to {max} exceeds the exact bound {bound} for dimension {dimension}")]
    CoordinateTooLarge {
        /// Largest |coordinate| found.
        max: u64,
        /// Largest supported |coordinate| for this dimension.
        bound: i64,
        /// Dimension.
        dimension: usize,
    },
    /// More simplices than fit a `u32` index.
    #[error("{0} simplices exceed the supported maximum of 2^32 - 1")]
    TooManySimplices(usize),
    /// An operating-system worker thread could not be started.
    #[error("could not start intersection worker: {0}")]
    ThreadSpawn(std::io::ErrorKind),
    /// An internal invariant of the kernel failed. This indicates a bug.
    #[error("internal invariant of the intersection kernel violated")]
    Internal,
}

/// Exact integer lane. Operations wrap, but callers only use them on inputs
/// within the generated coordinate bounds, where no intermediate can wrap.
trait Lane: Copy + Ord + Send + Sync {
    const ZERO: Self;
    fn add(self, other: Self) -> Self;
    fn sub(self, other: Self) -> Self;
    fn mul(self, other: Self) -> Self;
    fn neg(self) -> Self;
    fn from_i64(value: i64) -> Self;
}

impl Lane for i64 {
    const ZERO: Self = 0;
    #[inline(always)]
    fn add(self, other: Self) -> Self {
        self.wrapping_add(other)
    }
    #[inline(always)]
    fn sub(self, other: Self) -> Self {
        self.wrapping_sub(other)
    }
    #[inline(always)]
    fn mul(self, other: Self) -> Self {
        self.wrapping_mul(other)
    }
    #[inline(always)]
    fn neg(self) -> Self {
        self.wrapping_neg()
    }
    #[inline(always)]
    fn from_i64(value: i64) -> Self {
        value
    }
}

impl Lane for i128 {
    const ZERO: Self = 0;
    #[inline(always)]
    fn add(self, other: Self) -> Self {
        self.wrapping_add(other)
    }
    #[inline(always)]
    fn sub(self, other: Self) -> Self {
        self.wrapping_sub(other)
    }
    #[inline(always)]
    fn mul(self, other: Self) -> Self {
        self.wrapping_mul(other)
    }
    #[inline(always)]
    fn neg(self) -> Self {
        self.wrapping_neg()
    }
    #[inline(always)]
    fn from_i64(value: i64) -> Self {
        Self::from(value)
    }
}

/// Generalized cross product in dimension `D`: the normal of the hyperplane
/// spanned by `span[0..D-1]` (row 0 is the first spanning vector).
trait Gcross<const D: usize> {
    fn gcross<T: Lane>(span: &[[T; D]; D]) -> [T; D];
}

/// Whether some cross axis of two `D`-simplices separates them: the
/// generalized cross product of a k-face of one and an l-face of the other,
/// `k + l = D - 1`, computed from their k x k and l x l minors. Generated by
/// `build.rs`: straight-line code up to dimension 6, otherwise
/// [`cross_separated_generic`]. `None` only if an internal invariant fails.
trait CrossAxes<const D: usize, const V: usize> {
    fn cross_separated<T: Lane>(a: &[[T; D]; V], b: &[[T; D]; V]) -> Option<bool>;
}

/// Carrier type for the generated `Gcross` and `CrossAxes` implementations.
struct Dims;

#[inline(always)]
fn sub_vec<T: Lane, const D: usize>(a: &[T; D], b: &[T; D]) -> [T; D] {
    let mut out = [T::ZERO; D];
    for ((o, &x), &y) in out.iter_mut().zip(a).zip(b) {
        *o = x.sub(y);
    }
    out
}

#[inline(always)]
fn dot<T: Lane, const D: usize>(a: &[T; D], b: &[T; D]) -> T {
    a.iter()
        .zip(b)
        .fold(T::ZERO, |acc, (&x, &y)| acc.add(x.mul(y)))
}

#[inline(always)]
fn is_zero<T: Lane, const D: usize>(a: &[T; D]) -> bool {
    a.iter().all(|&x| x == T::ZERO)
}

/// Whether `axis` separates the two vertex sets (touching counts as
/// separated). Exits as soon as `b` is known to straddle `a`'s range: the axis
/// does not separate iff some projection of `b` lies above `min(a)` and some
/// lies below `max(a)`.
#[inline(always)]
fn separates<T: Lane, const D: usize, const V: usize>(
    a: &[[T; D]; V],
    b: &[[T; D]; V],
    axis: &[T; D],
) -> bool {
    let (min_a, max_a) = extent(a, axis);
    let (mut above, mut below) = (false, false);
    for v in b {
        let p = dot(v, axis);
        above |= p > min_a;
        below |= p < max_a;
        if above && below {
            return false;
        }
    }
    true
}

#[inline(always)]
fn extent<T: Lane, const D: usize, const V: usize>(verts: &[[T; D]; V], axis: &[T; D]) -> (T, T) {
    let mut projections = verts.iter().map(|v| dot(v, axis));
    let first = projections.next().unwrap_or(T::ZERO);
    projections.fold((first, first), |(lo, hi), p| (lo.min(p), hi.max(p)))
}

/// A simplex with its precomputed facet normals and bounding box.
#[derive(Clone, Copy)]
struct Prepared<T, const D: usize, const V: usize> {
    verts: [[T; D]; V],
    /// Outward facet normal opposite each vertex; zero if the facet is degenerate.
    normals: [[T; D]; V],
    lo: [T; D],
    hi: [T; D],
    /// Sum of the vertices, i.e. `V` times the centroid.
    sum: [T; D],
    /// `V * dot(normal, point on facet)` per facet: a point `p / V` is
    /// strictly inside this simplex iff `dot(normal, p) < offset` for every
    /// facet.
    offsets: [T; V],
    /// Whether the simplex is full-dimensional (nonzero volume).
    solid: bool,
}

fn prepare<T: Lane, const D: usize, const V: usize>(verts: [[T; D]; V]) -> Option<Prepared<T, D, V>>
where
    Dims: Gcross<D>,
{
    let mut normals = [[T::ZERO; D]; V];
    let mut solid = true;
    for (off, normal) in normals.iter_mut().enumerate() {
        let base = usize::from(off == 0);
        let origin = verts.get(base)?;
        let mut span = [[T::ZERO; D]; D];
        let mut rows = span.iter_mut();
        for (t, v) in verts.iter().enumerate() {
            if t != off && t != base {
                *rows.next()? = sub_vec(v, origin);
            }
        }
        let mut n = Dims::gcross(&span);
        // `orientation` is +- the simplex volume times D!, so it is zero for
        // every facet exactly when the simplex is flat.
        let orientation = dot(&n, &sub_vec(verts.get(off)?, origin));
        solid &= orientation != T::ZERO;
        if orientation > T::ZERO {
            n.iter_mut().for_each(|x| *x = x.neg());
        }
        *normal = n;
    }
    let (first, rest) = verts.split_first()?;
    let (mut lo, mut hi) = (*first, *first);
    for v in rest {
        for ((l, h), &x) in lo.iter_mut().zip(hi.iter_mut()).zip(v) {
            *l = (*l).min(x);
            *h = (*h).max(x);
        }
    }
    let mut sum = [T::ZERO; D];
    for v in &verts {
        for (acc, &x) in sum.iter_mut().zip(v) {
            *acc = acc.add(x);
        }
    }
    let scale = T::from_i64(i64::try_from(V).ok()?);
    let mut offsets = [T::ZERO; V];
    for (off, (offset, normal)) in offsets.iter_mut().zip(&normals).enumerate() {
        let base = verts.get(usize::from(off == 0))?;
        *offset = scale.mul(dot(normal, base));
    }
    Some(Prepared {
        verts,
        normals,
        lo,
        hi,
        sum,
        offsets,
        solid,
    })
}

/// Whether the point `p / (scale * V)` lies strictly inside the
/// full-dimensional simplex `s`.
#[inline(always)]
fn strictly_inside<T: Lane, const D: usize, const V: usize>(
    p: &[T; D],
    scale: T,
    s: &Prepared<T, D, V>,
) -> bool {
    s.normals
        .iter()
        .zip(&s.offsets)
        .all(|(normal, &offset)| dot(normal, p) < scale.mul(offset))
}

/// Exact witness of intersecting interiors: a point strictly inside both
/// simplices. Tries the centroid of each simplex inside the other, then the
/// points `(i c_a + (N - i) c_b) / N`, `i = 1..N`, between the centroids
/// (`N = WITNESS_STEPS`). Most overlapping pairs are settled here without
/// enumerating the cross axes.
#[inline(always)]
fn witnessed<T: Lane, const D: usize, const V: usize>(
    a: &Prepared<T, D, V>,
    b: &Prepared<T, D, V>,
) -> bool {
    let one = T::from_i64(1);
    if (b.solid && strictly_inside(&a.sum, one, b)) || (a.solid && strictly_inside(&b.sum, one, a))
    {
        return true;
    }
    if !(a.solid && b.solid) {
        return false;
    }
    let steps = T::from_i64(WITNESS_STEPS);
    (1..WITNESS_STEPS)
        .zip((1..WITNESS_STEPS).rev())
        .any(|(i, j)| {
            let (wa, wb) = (T::from_i64(i), T::from_i64(j));
            let mut p = [T::ZERO; D];
            for ((x, &sa), &sb) in p.iter_mut().zip(&a.sum).zip(&b.sum) {
                *x = wa.mul(sa).add(wb.mul(sb));
            }
            strictly_inside(&p, steps, a) && strictly_inside(&p, steps, b)
        })
}

/// All `size x size` minors of the spanning vectors of `face` (a list of
/// `size + 1` vertex indices), one per coordinate subset in `sets`.
fn face_minors<T: Lane, const D: usize, const V: usize>(
    verts: &[[T; D]; V],
    face: &[u8],
    size: usize,
    sets: &[u8],
    out: &mut [T],
) -> Option<()> {
    let (&first, rest) = face.split_first()?;
    let origin = verts.get(usize::from(first))?;
    let mut vectors = [[T::ZERO; D]; MAX_MINOR];
    for (row, &idx) in vectors.iter_mut().zip(rest) {
        *row = sub_vec(verts.get(usize::from(idx))?, origin);
    }
    if size == 1 {
        let v = vectors.first()?;
        for (dst, &component) in out.iter_mut().zip(sets) {
            *dst = *v.get(usize::from(component))?;
        }
        return Some(());
    }
    for (dst, set) in out.iter_mut().zip(sets.chunks_exact(size)) {
        let mut m = [[T::ZERO; MAX_MINOR]; MAX_MINOR];
        for (row, &component) in m.iter_mut().zip(set) {
            for (cell, v) in row.iter_mut().zip(vectors.iter().take(size)) {
                *cell = *v.get(usize::from(component))?;
            }
        }
        *dst = small_det(&m, size)?;
    }
    Some(())
}

/// Table-driven cross-axis enumeration for dimensions above 6: whether some
/// cross axis separates the vertex sets. Each axis is computed by the
/// generalized Laplace expansion from the k x k minors of the a-face and the
/// l x l minors of the b-face; the b-face minors are computed once per k,
/// the a-face minors once per a-face. `None` only if an internal invariant
/// fails.
fn cross_separated_generic<T: Lane, const D: usize, const V: usize>(
    a: &[[T; D]; V],
    b: &[[T; D]; V],
) -> Option<bool> {
    let (mut minors_of_a, mut minors_of_b) = (Vec::new(), Vec::new());
    let top = D.checked_sub(1)?;
    for k in 1..top {
        let l = top.checked_sub(k)?;
        let (size_a, size_b) = (k.checked_add(1)?, l.checked_add(1)?);
        let (faces_a, faces_b) = (faces(V, size_a), faces(V, size_b));
        let (sub_a, sub_b) = (subsets(D, k), subsets(D, l));
        let terms = cross_terms(D, k);
        let minors_a = sub_a.len().checked_div(k)?;
        let minors_b = sub_b.len().checked_div(l)?;
        let per_component = terms.len().checked_div(D)?;
        if faces_a.is_empty() || faces_b.is_empty() || per_component == 0 {
            return None;
        }
        let n_faces_b = faces_b.len().checked_div(size_b)?;
        minors_of_b.resize(n_faces_b.checked_mul(minors_b)?, T::ZERO);
        minors_of_a.resize(minors_a, T::ZERO);
        for (face, out) in faces_b
            .chunks_exact(size_b)
            .zip(minors_of_b.chunks_exact_mut(minors_b))
        {
            face_minors(b, face, l, sub_b, out)?;
        }
        for face in faces_a.chunks_exact(size_a) {
            face_minors(a, face, k, sub_a, &mut minors_of_a)?;
            for b_minors in minors_of_b.chunks_exact(minors_b) {
                let mut axis = [T::ZERO; D];
                for (component, group) in axis.iter_mut().zip(terms.chunks_exact(per_component)) {
                    let mut acc = T::ZERO;
                    for &(ia, ib, positive) in group {
                        let product = minors_of_a
                            .get(usize::from(ia))?
                            .mul(*b_minors.get(usize::from(ib))?);
                        acc = if positive {
                            acc.add(product)
                        } else {
                            acc.sub(product)
                        };
                    }
                    *component = acc;
                }
                if !is_zero(&axis) && separates(a, b, &axis) {
                    return Some(true);
                }
            }
        }
    }
    Some(false)
}

/// Exact separating-axis test. `None` only if an internal invariant fails.
fn intersects<T: Lane, const D: usize, const V: usize>(
    a: &Prepared<T, D, V>,
    b: &Prepared<T, D, V>,
) -> Option<bool>
where
    Dims: CrossAxes<D, V>,
{
    let boxes_apart =
        a.hi.iter().zip(&b.lo).any(|(h, l)| h <= l) || b.hi.iter().zip(&a.lo).any(|(h, l)| h <= l);
    if boxes_apart {
        return Some(false);
    }
    for (n1, n2) in a.normals.iter().zip(&b.normals) {
        if !is_zero(n1) && separates(&a.verts, &b.verts, n1) {
            return Some(false);
        }
        if !is_zero(n2) && separates(&a.verts, &b.verts, n2) {
            return Some(false);
        }
    }
    if D == 2 || witnessed(a, b) {
        return Some(true);
    }
    Some(!Dims::cross_separated(&a.verts, &b.verts)?)
}

/// All pairs `(i, j)`, `i < j`, of simplices whose interiors intersect.
///
/// `points` is a row-major `n x dimension` coordinate matrix and `simplices`
/// a flat list of `dimension + 1` zero-based point labels per simplex. The
/// result is sorted lexicographically and independent of the thread count.
pub fn intersecting_pairs(
    points: &[i64],
    dimension: usize,
    simplices: &[u32],
) -> Result<Vec<(u32, u32)>, IntersectError> {
    dispatch(points, dimension, simplices, Job::Collect)
}

/// The pairs of [`intersecting_pairs`], one row at a time, for consumers that
/// use them while they are computed (incremental solving).
///
/// `workers` threads (at least one) take the rows `i` (simplex `i` against
/// every later simplex) in increasing order from a shared counter and pass
/// each nonempty row's pairs, increasing, to `sink`. Rows reach `sink` in no
/// particular order and from several threads at once. The search ends when
/// every row is done or as soon as `sink` returns `false`.
pub fn stream_pairs(
    points: &[i64],
    dimension: usize,
    simplices: &[u32],
    workers: usize,
    sink: RowSink<'_>,
) -> Result<(), IntersectError> {
    dispatch(points, dimension, simplices, Job::Stream { workers, sink }).map(drop)
}

/// Receives the rows of [`stream_pairs`]; returns whether to go on.
pub type RowSink<'a> = &'a (dyn Fn(&[(u32, u32)]) -> bool + Sync);

/// What [`search_lane`] does with the rows.
#[derive(Clone, Copy)]
enum Job<'a> {
    /// Collect all pairs in order.
    Collect,
    /// Hand rows to `sink` from `workers` threads; collects nothing.
    Stream { workers: usize, sink: RowSink<'a> },
}

fn dispatch(
    points: &[i64],
    dimension: usize,
    simplices: &[u32],
    job: Job<'_>,
) -> Result<Vec<(u32, u32)>, IntersectError> {
    match dimension {
        2 => search::<2, 3>(points, simplices, job),
        3 => search::<3, 4>(points, simplices, job),
        4 => search::<4, 5>(points, simplices, job),
        5 => search::<5, 6>(points, simplices, job),
        6 => search::<6, 7>(points, simplices, job),
        7 => search::<7, 8>(points, simplices, job),
        8 => search::<8, 9>(points, simplices, job),
        9 => search::<9, 10>(points, simplices, job),
        10 => search::<10, 11>(points, simplices, job),
        _ => Err(IntersectError::UnsupportedDimension(dimension)),
    }
}

fn search<const D: usize, const V: usize>(
    points: &[i64],
    simplices: &[u32],
    job: Job<'_>,
) -> Result<Vec<(u32, u32)>, IntersectError>
where
    Dims: Gcross<D> + CrossAxes<D, V>,
{
    if points.len().checked_rem(D) != Some(0) {
        return Err(IntersectError::PointShape {
            len: points.len(),
            dimension: D,
        });
    }
    if simplices.len().checked_rem(V) != Some(0) {
        return Err(IntersectError::SimplexShape {
            len: simplices.len(),
            vertices: V,
        });
    }
    let max = points.iter().map(|x| x.unsigned_abs()).max().unwrap_or(0);
    let bound_64 = COORD_BOUND_I64
        .get(D)
        .copied()
        .ok_or(IntersectError::Internal)?;
    let bound_128 = COORD_BOUND_I128
        .get(D)
        .copied()
        .ok_or(IntersectError::Internal)?;
    if max <= bound_64.unsigned_abs() {
        search_lane::<i64, D, V>(points, simplices, job)
    } else if max <= bound_128.unsigned_abs() {
        search_lane::<i128, D, V>(points, simplices, job)
    } else {
        Err(IntersectError::CoordinateTooLarge {
            max,
            bound: bound_128,
            dimension: D,
        })
    }
}

fn search_lane<T: Lane, const D: usize, const V: usize>(
    points: &[i64],
    simplices: &[u32],
    job: Job<'_>,
) -> Result<Vec<(u32, u32)>, IntersectError>
where
    Dims: Gcross<D> + CrossAxes<D, V>,
{
    let n_points = points
        .len()
        .checked_div(D)
        .ok_or(IntersectError::Internal)?;
    let prepared = simplices
        .chunks_exact(V)
        .enumerate()
        .map(|(s, labels)| {
            let mut verts = [[T::ZERO; D]; V];
            for (vert, &label) in verts.iter_mut().zip(labels) {
                let start = usize::try_from(label)
                    .ok()
                    .and_then(|l| l.checked_mul(D))
                    .ok_or(IntersectError::Internal)?;
                let row = points.get(start..start.saturating_add(D)).ok_or(
                    IntersectError::PointOutOfRange {
                        simplex: s,
                        label,
                        points: n_points,
                    },
                )?;
                for (c, &x) in vert.iter_mut().zip(row) {
                    *c = T::from_i64(x);
                }
            }
            prepare(verts).ok_or(IntersectError::Internal)
        })
        .collect::<Result<Vec<_>, _>>()?;
    let n = prepared.len();
    if u32::try_from(n).is_err() {
        return Err(IntersectError::TooManySimplices(n));
    }
    let row = |i: usize| -> Result<Vec<(u32, u32)>, IntersectError> {
        let a = prepared.get(i).ok_or(IntersectError::Internal)?;
        let ia = u32::try_from(i).map_err(|_| IntersectError::Internal)?;
        let mut out = Vec::new();
        for (j, b) in prepared.iter().enumerate().skip(i.saturating_add(1)) {
            if intersects(a, b).ok_or(IntersectError::Internal)? {
                out.push((ia, u32::try_from(j).map_err(|_| IntersectError::Internal)?));
            }
        }
        Ok(out)
    };
    let (workers, sink) = match job {
        Job::Collect => {
            // A one-thread pool only adds scheduling overhead (about 60% on
            // a 248-simplex 3D case), so it runs serially too.
            let rows: Vec<Vec<(u32, u32)>> =
                if n < PARALLEL_THRESHOLD || rayon::current_num_threads() <= 1 {
                    (0..n).map(row).collect::<Result<_, _>>()?
                } else {
                    (0..n).into_par_iter().map(row).collect::<Result<_, _>>()?
                };
            return Ok(rows.into_iter().flatten().collect());
        }
        Job::Stream { workers, sink } => (workers.max(1), sink),
    };
    stream_rows(n, workers, sink, row, |_| Ok(std::thread::Builder::new()))?;
    Ok(Vec::new())
}

/// Start every worker before allowing sink calls. If creation fails partway,
/// workers exit through the gate instead of blocking in a consumer that is
/// still waiting for startup to finish.
fn stream_rows(
    n: usize,
    workers: usize,
    sink: RowSink<'_>,
    row: impl Fn(usize) -> Result<Vec<(u32, u32)>, IntersectError> + Sync,
    builder: impl Fn(usize) -> std::io::Result<std::thread::Builder>,
) -> Result<(), IntersectError> {
    let next = AtomicUsize::new(0);
    let done = AtomicBool::new(false);
    let failure = Mutex::new(None);
    let ready = Mutex::new(false);
    let started = Condvar::new();
    std::thread::scope(|scope| {
        let mut handles = Vec::new();
        for worker in 0..workers.min(n) {
            let spawned = builder(worker).and_then(|builder| {
                builder.spawn_scoped(scope, || {
                    let mut released = ready.lock().unwrap_or_else(PoisonError::into_inner);
                    while !*released {
                        released = started
                            .wait(released)
                            .unwrap_or_else(PoisonError::into_inner);
                    }
                    drop(released);
                    while !done.load(Ordering::Relaxed) {
                        let i = next.fetch_add(1, Ordering::Relaxed);
                        if i >= n {
                            break;
                        }
                        let keep_going = match row(i) {
                            Ok(pairs) => pairs.is_empty() || sink(&pairs),
                            Err(error) => {
                                failure
                                    .lock()
                                    .unwrap_or_else(PoisonError::into_inner)
                                    .get_or_insert(error);
                                false
                            }
                        };
                        if !keep_going {
                            done.store(true, Ordering::Relaxed);
                        }
                    }
                })
            });
            match spawned {
                Ok(handle) => handles.push(handle),
                Err(error) => {
                    failure
                        .lock()
                        .unwrap_or_else(PoisonError::into_inner)
                        .get_or_insert(IntersectError::ThreadSpawn(error.kind()));
                    done.store(true, Ordering::Relaxed);
                    break;
                }
            }
        }
        *ready.lock().unwrap_or_else(PoisonError::into_inner) = true;
        started.notify_all();
        for handle in handles {
            if handle.join().is_err() {
                done.store(true, Ordering::Relaxed);
                failure
                    .lock()
                    .unwrap_or_else(PoisonError::into_inner)
                    .get_or_insert(IntersectError::Internal);
            }
        }
    });
    match failure.into_inner().unwrap_or_else(PoisonError::into_inner) {
        Some(error) => Err(error),
        None => Ok(()),
    }
}

